#!/usr/bin/env node
// Requirement → test coverage matrix (SPEC §25.3, §26.1; STATE.md F0.11).
//
//   node scripts/coverage-matrix.mjs           # check (verify step)
//   node scripts/coverage-matrix.mjs --write   # regenerate docs/testing.md section
//
// Reads requirement and AC rows from SPEC.md and the links from
// docs/coverage.json. Fails when a P0 requirement, INV or NFR has no link,
// when a link names an unknown AC/MT/BM, or when docs/testing.md is stale.
// "Test reference" means a test file mentions the AC/MT/BM id or the
// requirement id; it does not mean the AC is met. Also checks that the
// documents SPEC §27 requires by M0 exist.

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const write = process.argv.includes("--write");
const spec = readFileSync(join(root, "SPEC.md"), "utf8").split(/\r?\n/);
const cov = JSON.parse(readFileSync(join(root, "docs", "coverage.json"), "utf8"));

// | ID | text | ... |   (requirements, INV, NFR, AC)
const rows = new Map();
for (const line of spec) {
  const m = /^\| ((?:AC|INV|NFR|CAP|IMP|ORG|SEA|DL|PLAY|DATA)-\d+) \| (.*) \|\s*$/.exec(line);
  if (!m) continue;
  const cells = m[2].split(" | ");
  rows.set(m[1], cells);
}
const ac = new Set([...rows.keys()].filter((k) => k.startsWith("AC-")));
const short = (t, n = 90) => {
  const s = t.replace(/`/g, "").replace(/\*\*/g, "").replace(/\|/g, "/");
  return s.length > n ? `${s.slice(0, n - 1).trimEnd()}…` : s;
};

/** @type {{id:string, stage:string, text:string}[]} */
const scope = [];
for (const [id, cells] of rows) {
  if (id.startsWith("AC-")) continue;
  if (/^(INV|NFR)-/.test(id)) {
    scope.push({ id, stage: id.startsWith("INV") ? "tüm aşamalar" : "M0–M4", text: id.startsWith("NFR") ? `${cells[0]}: ${cells[1]}` : cells[0] });
  } else {
    const stage = cells[cells.length - 1];
    if (/\bP0\b/.test(stage)) scope.push({ id, stage: stage.replace(/\s*\/\s*P0/, ""), text: cells[0] });
  }
}

// Test files and the ids they mention.
const testFile = (p) =>
  /(^|\/)tests\//.test(p) || /\.(spec|test)\.tsx?$/.test(p) || /^scripts\/.*-probe\.mjs$/.test(p) || (p.endsWith(".rs") && /#\[(test|cfg\(test\))\]/.test(readFileSync(join(root, p), "utf8")));
const skipDirs = new Set(["node_modules", "target", ".git", "dist", "test-artifacts", "gen", "fixtures"]);
const files = [];
(function walk(d) {
  for (const n of readdirSync(join(root, d))) {
    if (skipDirs.has(n)) continue;
    const p = d ? `${d}/${n}` : n;
    if (statSync(join(root, p)).isDirectory()) walk(p);
    else if (/\.(rs|ts|tsx|mjs)$/.test(n) && testFile(p)) files.push(p);
  }
})("");
const mentions = new Map();
for (const f of files) {
  const text = readFileSync(join(root, f), "utf8");
  for (const m of text.matchAll(/\b(AC|MT|BM|INV|NFR|CAP|IMP|ORG|SEA|DL|PLAY|DATA)-\d+\b/g)) {
    if (!mentions.has(m[0])) mentions.set(m[0], new Set());
    mentions.get(m[0]).add(f);
  }
}
for (const [id, t] of Object.entries(cov.manualTests)) if (t.automated) for (const f of t.automated.split(/,\s*/)) (mentions.get(id) ?? mentions.set(id, new Set()).get(id)).add(f);

const errors = [];
// SPEC §27: documents due by M0 (STATE.md F0.11).
for (const d of ["architecture", "decisions", "threat-model", "roadmap", "platform-support", "testing"]) {
  if (!existsSync(join(root, "docs", `${d}.md`))) errors.push(`docs/${d}.md is missing (SPEC §27, due by M0)`);
}
const known = (l) => ac.has(l) || l in cov.manualTests || l in cov.benchmarks;
for (const r of scope) {
  const links = cov.links[r.id];
  if (!links?.length) errors.push(`${r.id} (${r.stage}) has no AC, manual test or benchmark in docs/coverage.json`);
  for (const l of links ?? []) if (!known(l)) errors.push(`${r.id} links to unknown ${l}`);
}
for (const id of Object.keys(cov.links)) if (!scope.some((r) => r.id === id)) errors.push(`docs/coverage.json links ${id}, which is not a P0/INV/NFR row in SPEC.md`);

const evidence = (r) => {
  const out = new Set();
  for (const id of [r.id, ...(cov.links[r.id] ?? [])]) for (const f of mentions.get(id) ?? []) out.add(f);
  return [...out].sort();
};
const linkText = (l) => (ac.has(l) ? l : l in cov.manualTests ? `${l}` : `${l}`);

const covered = scope.filter((r) => cov.links[r.id]?.length).length;
const withTests = scope.filter((r) => evidence(r).length).length;
const lines = [
  "<!-- coverage:begin (generated by scripts/coverage-matrix.mjs; edit docs/coverage.json) -->",
  "",
  `Kapsam: SPEC §7'deki P0 gereksinimler, §5'teki tüm değişmezler (INV) ve §22'deki tüm NFR'ler, toplam ${scope.length}. Bağlantısı olan: **${covered}/${scope.length}**. Bağlı kimliklerden birine ya da gereksinimin kendisine atıf yapan bir test dosyası olan: **${withTests}/${scope.length}**.`,
  "",
  "\"Test atfı\" sütunu yalnızca o kimliği anan test dosyalarını listeler. Bir AC'nin karşılandığını göstermez; karşılanma durumu STATE.md'deki alt görevin kanıtıyla belirlenir.",
  "",
  "| Gereksinim | Aşama | Özet | Bağlı AC / test | Test atfı |",
  "|---|---|---|---|---|",
  ...scope.map((r) => {
    const ev = evidence(r);
    return `| ${r.id} | ${r.stage} | ${short(r.text)} | ${(cov.links[r.id] ?? []).map(linkText).join(", ") || "**yok**"} | ${ev.length ? ev.map((f) => `\`${f}\``).join(", ") : "henüz yok"} |`;
  }),
  "",
  "### Kimlikli manuel testler (MT)",
  "",
  "| Kimlik | Test | Adımlar | Otomasyon |",
  "|---|---|---|---|",
  ...Object.entries(cov.manualTests).map(([id, t]) => `| ${id} | ${t.title} | ${t.steps} | ${t.automated ? t.automated.split(/,\s*/).map((f) => `\`${f}\``).join(", ") : "elle"} |`),
  "",
  "### Benchmark'lar (BM)",
  "",
  "| Kimlik | Ölçüm | NFR |",
  "|---|---|---|",
  ...Object.entries(cov.benchmarks).map(([id, b]) => `| ${id} | ${b.title} | ${b.spec} |`),
  "",
  "<!-- coverage:end -->",
];
const generated = lines.join("\n");

const testingPath = join(root, "docs", "testing.md");
const testing = readFileSync(testingPath, "utf8");
const re = /<!-- coverage:begin[\s\S]*?<!-- coverage:end -->/;
if (!re.test(testing)) errors.push("docs/testing.md has no <!-- coverage:begin --> … <!-- coverage:end --> section");
const next = testing.replace(re, generated);

if (write) {
  if (next !== testing) writeFileSync(testingPath, next);
  console.log(`docs/testing.md: ${covered}/${scope.length} linked, ${withTests}/${scope.length} with a test reference`);
} else if (next !== testing) {
  errors.push("docs/testing.md coverage section is stale: run npm run coverage:write");
}
if (errors.length) {
  for (const e of errors) console.error(`✗ ${e}`);
  process.exit(1);
}
if (!write) console.log(`✓ coverage matrix: ${covered}/${scope.length} linked, ${withTests}/${scope.length} with a test reference (${files.length} test files scanned)`);
