//! Versioned benchmark data generator (SPEC §25.2, NFR-01…07, DEC-17;
//! STATE.md F0.12, ADR-0009).
//!
//! The same `(GENERATOR_VERSION, seed, counts)` always gives the same bytes,
//! on every OS: own PRNG ([`rng`]), integers only, ordered JSON, `\n` line
//! ends. Any change to the output must bump `GENERATOR_VERSION` and the
//! golden hashes in `tests/fixtures/benchdata/golden.json`.
//!
//! The rows follow a benchmark schema of their own ("bench schema v1"). The
//! library schema (STATE.md F1.1) does not exist yet; once it does, a loader
//! maps these rows onto it and the benchmarks run against the real tables.

pub mod bench;
pub mod rng;
pub mod words;

use rng::Rng;
use serde::Serialize;
use sha2::{Digest, Sha256};
use std::io::{self, Write};

/// Bump on any change that alters generated bytes.
pub const GENERATOR_VERSION: u32 = 1;
pub const DEFAULT_SEED: u64 = 20_261_107;
/// SPEC §25.2: 10.000 items and 100.000 transcript segments.
pub const DEFAULT_ITEMS: u32 = 10_000;
pub const DEFAULT_SEGMENTS: u32 = 100_000;
/// 2026-01-01T00:00:00Z; `createdAt` values count forward from here.
const EPOCH_BASE: u64 = 1_767_225_600;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Params {
    pub seed: u64,
    pub items: u32,
    pub segments: u32,
}

impl Default for Params {
    fn default() -> Params {
        Params {
            seed: DEFAULT_SEED,
            items: DEFAULT_ITEMS,
            segments: DEFAULT_SEGMENTS,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Item {
    pub id: u32,
    /// `bookmark`, `local_video` or `downloaded`.
    pub kind: &'static str,
    pub platform: &'static str,
    pub source_url: Option<String>,
    pub title: String,
    pub description: String,
    pub note: Option<String>,
    pub tags: Vec<&'static str>,
    pub collections: Vec<&'static str>,
    /// Unknown for some items, as in real libraries.
    pub duration_ms: Option<u64>,
    /// `tr`, `en` or `mixed`.
    pub language: &'static str,
    /// Unix seconds.
    pub created_at: u64,
    pub favorite: bool,
    pub archived: bool,
    pub has_thumbnail: bool,
    /// `pending`, `ok` or `failed` (CAP-04).
    pub metadata_status: &'static str,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Segment {
    pub item_id: u32,
    pub index: u32,
    pub start_ms: u64,
    pub end_ms: u64,
    pub language: &'static str,
    pub text: String,
}

pub struct Dataset {
    pub params: Params,
    pub items: Vec<Item>,
    pub segments: Vec<Segment>,
}

fn words(r: &mut Rng, lang: &str, n: u64) -> Vec<&'static str> {
    (0..n)
        .map(|_| match lang {
            "tr" => *r.pick(words::TR),
            "en" => *r.pick(words::EN),
            _ => {
                if r.chance(50) {
                    *r.pick(words::TR)
                } else {
                    *r.pick(words::EN)
                }
            }
        })
        .collect()
}

fn capitalise_first(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        // Turkish rule for the one letter where it differs.
        Some('i') => format!("İ{}", c.as_str()),
        Some(f) => f.to_uppercase().chain(c).collect(),
        None => String::new(),
    }
}

/// Same text in Unicode NFD for the letters the Turkish fixtures care about
/// (SPEC §25.2: NFC and NFD forms of the same text).
fn to_nfd(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 8);
    for ch in s.chars() {
        match ch {
            'ü' => out.push_str("u\u{0308}"),
            'Ü' => out.push_str("U\u{0308}"),
            'ö' => out.push_str("o\u{0308}"),
            'Ö' => out.push_str("O\u{0308}"),
            'ç' => out.push_str("c\u{0327}"),
            'Ç' => out.push_str("C\u{0327}"),
            'ş' => out.push_str("s\u{0327}"),
            'Ş' => out.push_str("S\u{0327}"),
            'ğ' => out.push_str("g\u{0306}"),
            'İ' => out.push_str("I\u{0307}"),
            c => out.push(c),
        }
    }
    out
}

fn sentence(r: &mut Rng, lang: &str, lo: u64, hi: u64) -> String {
    let n = r.range(lo, hi);
    let mut s = words(r, lang, n).join(" ");
    s = capitalise_first(&s);
    s.push('.');
    s
}

fn source_id(r: &mut Rng, len: usize) -> String {
    const A: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
    (0..len).map(|_| A[r.below(64) as usize] as char).collect()
}

fn item(r: &mut Rng, id: u32) -> Item {
    let language = match r.below(10) {
        0..=4 => "tr",
        5..=7 => "en",
        _ => "mixed",
    };
    let kind = match r.below(100) {
        0..=59 => "bookmark",
        60..=84 => "downloaded",
        _ => "local_video",
    };
    let (platform, host) = if kind == "local_video" {
        ("local", "")
    } else {
        *r.pick(words::PLATFORMS)
    };
    let source_url = (kind != "local_video").then(|| {
        let sid = source_id(r, 11);
        format!("https://{host}/v/{sid}")
    });

    // Titles: mostly 3–10 words, 3 % very long (SPEC §25.2), some emoji.
    let mut title = if r.chance(3) {
        words(r, language, 60).join(" ")
    } else {
        let n = r.range(3, 10);
        words(r, language, n).join(" ")
    };
    title = capitalise_first(&title);
    if r.chance(8) {
        title = format!("{} {title}", r.pick(words::EMOJI));
    }
    if language == "tr" && r.chance(2) {
        title = to_nfd(&title);
    }
    let description = if r.chance(15) {
        String::new()
    } else {
        let n = r.range(1, 4);
        (0..n)
            .map(|_| sentence(r, language, 6, 18))
            .collect::<Vec<_>>()
            .join(" ")
    };
    let note = r.chance(20).then(|| sentence(r, language, 4, 25));

    let mut tags: Vec<&'static str> = Vec::new();
    for _ in 0..r.below(5) {
        let t = *r.pick(words::TAGS);
        if !tags.contains(&t) {
            tags.push(t);
        }
    }
    let mut collections: Vec<&'static str> = Vec::new();
    for _ in 0..r.below(3) {
        let c = *r.pick(words::COLLECTIONS);
        if !collections.contains(&c) {
            collections.push(c);
        }
    }
    let duration_ms = (!r.chance(10)).then(|| r.range(15, 3 * 3600) * 1000 + r.below(1000));
    let metadata_status = if kind == "bookmark" {
        match r.below(10) {
            0..=5 => "ok",
            6..=8 => "pending",
            _ => "failed",
        }
    } else {
        "ok"
    };
    Item {
        id,
        kind,
        platform,
        source_url,
        title,
        description,
        note,
        tags,
        collections,
        duration_ms,
        language,
        // Spread over ~10 months, strictly increasing with id.
        created_at: EPOCH_BASE + id as u64 * 2_600 + r.below(2_600),
        favorite: r.chance(7),
        archived: r.chance(12),
        has_thumbnail: kind != "bookmark" || !r.chance(30),
        metadata_status,
    }
}

/// Splits `total` segments over items that have local media, in order.
fn segments(r: &mut Rng, items: &[Item], total: u32) -> Vec<Segment> {
    let media: Vec<&Item> = items.iter().filter(|i| i.kind != "bookmark").collect();
    let mut out = Vec::with_capacity(total as usize);
    if media.is_empty() || total == 0 {
        return out;
    }
    // Each media item gets a share; leftovers go to the first items.
    let base = total / media.len() as u32;
    let mut extra = total % media.len() as u32;
    for it in media {
        let mut n = base;
        if extra > 0 {
            n += 1;
            extra -= 1;
        }
        let lang = if it.language == "mixed" {
            if r.chance(50) {
                "tr"
            } else {
                "en"
            }
        } else {
            it.language
        };
        let mut t = r.below(3_000);
        for index in 0..n {
            let len = r.range(1_500, 8_000);
            out.push(Segment {
                item_id: it.id,
                index,
                start_ms: t,
                end_ms: t + len,
                language: lang,
                text: sentence(r, lang, 5, 16),
            });
            t += len + r.below(400);
        }
    }
    out
}

pub fn generate(p: Params) -> Dataset {
    // Separate streams so a change in segment rules cannot shift items.
    let mut ri = Rng::new(p.seed ^ 0x6974_656D_7300_0001);
    let items: Vec<Item> = (1..=p.items).map(|id| item(&mut ri, id)).collect();
    let mut rs = Rng::new(p.seed ^ 0x7365_676D_6E74_0002);
    let segments = segments(&mut rs, &items, p.segments);
    Dataset {
        params: p,
        items,
        segments,
    }
}

/// One JSON object per line, `\n` line ends.
pub fn write_jsonl<T: Serialize>(rows: &[T], mut w: impl Write) -> io::Result<()> {
    for row in rows {
        serde_json::to_writer(&mut w, row)?;
        w.write_all(b"\n")?;
    }
    Ok(())
}

/// SHA-256 of what [`write_jsonl`] writes, without keeping it in memory.
pub fn jsonl_sha256<T: Serialize>(rows: &[T]) -> String {
    struct H(Sha256);
    impl Write for H {
        fn write(&mut self, b: &[u8]) -> io::Result<usize> {
            self.0.update(b);
            Ok(b.len())
        }
        fn flush(&mut self) -> io::Result<()> {
            Ok(())
        }
    }
    let mut h = H(Sha256::new());
    write_jsonl(rows, &mut h).expect("hashing cannot fail");
    h.0.finalize().iter().map(|b| format!("{b:02x}")).collect()
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Manifest {
    pub generator: &'static str,
    pub generator_version: u32,
    pub schema: &'static str,
    pub seed: u64,
    pub items: u32,
    pub segments: u32,
    pub items_sha256: String,
    pub segments_sha256: String,
}

impl Dataset {
    pub fn manifest(&self) -> Manifest {
        Manifest {
            generator: "vv-benchdata",
            generator_version: GENERATOR_VERSION,
            schema: "bench-v1",
            seed: self.params.seed,
            items: self.items.len() as u32,
            segments: self.segments.len() as u32,
            items_sha256: jsonl_sha256(&self.items),
            segments_sha256: jsonl_sha256(&self.segments),
        }
    }
}
